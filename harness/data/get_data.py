#!/usr/bin/env python3
"""Download the two source corpora. We do not redistribute them.

POPQUORN (Pei & Jurgens 2023) supplies the politeness items and the human age
brackets; the Measuring Hate Speech Corpus (Kennedy et al. 2020) supplies the
validation task in Appendix B. Both are public, both carry their own licences,
and both stay with their authors -- this script just fetches them into place.

POPQUORN is a static file in a git repository, so we pin its SHA-256: the
checksum below is the exact file the paper's results were computed from. The
MHSC parquet is generated by HuggingFace's conversion pipeline and can be
re-encoded without the data changing, so pinning its bytes would produce
confusing failures. We check its shape instead, which is what the analysis
actually depends on.

Usage: python3 get_data.py
"""

from __future__ import annotations

import hashlib
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent

POPQUORN_URL = ("https://raw.githubusercontent.com/Jiaxin-Pei/"
                "potato-prolific-dataset/main/dataset/politeness_rating/raw_data.csv")
POPQUORN_SHA256 = "beb7c68c6366ab27819cdf40fec7eb76676f5903c99dad95c13d4bd2bc28365f"
POPQUORN_DEST = HERE / "popquorn_politeness_raw.csv"

MHSC_URL = ("https://huggingface.co/api/datasets/ucberkeley-dlab/"
            "measuring-hate-speech/parquet/default/train/0.parquet")
MHSC_DEST = HERE / "mhsc.parquet"
MHSC_EXPECTED = {"rows": 135_556, "annotators": 7_912}


def fetch(url: str, dest: Path) -> None:
    if dest.exists():
        print(f"  {dest.name}: already present, skipping download")
        return
    print(f"  downloading {dest.name} ...")
    with urllib.request.urlopen(url, timeout=300) as r, open(dest, "wb") as f:
        f.write(r.read())


def main() -> int:
    print("POPQUORN politeness (Pei & Jurgens 2023)")
    fetch(POPQUORN_URL, POPQUORN_DEST)
    digest = hashlib.sha256(POPQUORN_DEST.read_bytes()).hexdigest()
    if digest == POPQUORN_SHA256:
        print("  sha256 OK -- byte-identical to the file used in the paper")
    else:
        print(f"  WARNING: sha256 mismatch\n    expected {POPQUORN_SHA256}\n"
              f"    got      {digest}\n  Upstream may have been revised; "
              "results below may not reproduce exactly.")

    print("\nMeasuring Hate Speech Corpus (Kennedy et al. 2020)")
    fetch(MHSC_URL, MHSC_DEST)
    try:
        import pandas as pd
        df = pd.read_parquet(MHSC_DEST)
        got = {"rows": len(df), "annotators": df["annotator_id"].nunique()}
        status = "OK" if got == MHSC_EXPECTED else "MISMATCH"
        print(f"  shape {status}: {got} (expected {MHSC_EXPECTED})")
    except ImportError:
        print("  pandas not installed; skipping shape check")

    print("\nNext: python3 ../rebuild_items.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
